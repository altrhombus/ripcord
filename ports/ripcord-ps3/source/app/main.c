/*
 * ports/common's own suites, on the console. See source/coretest/rc_core_tests.h for why this matters:
 * every assertion in the shared core has only ever run on little-endian x86, and the PPE is big-endian.
 *
 * THE RUNNERS PRINT WITH printf, which here goes to a TTY nobody is reading, so stdout is redirected to
 * a file for the duration and replayed through ps3_log afterwards - which puts it on the network log and
 * in both files, like everything else. Their output is the useful part when something fails: a bare exit
 * code would say "fec failed" and leave the next step to a rebuild.
 */
#define RC_CORE_TEST_CAPTURE "/dev_hdd0/ripcord-core-tests.txt"

static void replay_captured(const char *path)
{
    static char line[512];
    FILE *f = fopen(path, "r");

    if (f == NULL) {
        ps3_log("      (could not reopen %s to replay it)\n", path);
        return;
    }
    while (fgets(line, (int)sizeof(line), f) != NULL) {
        size_t n = strlen(line);
        while (n > 0u && (line[n - 1u] == '\n' || line[n - 1u] == '\r'))
            line[--n] = '\0';
        if (n > 0u)
            ps3_log("      | %s\n", line);
    }
    fclose(f);
}

static int check_core(void)
{
    rc_core_test_result results[RC_CORE_TEST_COUNT];
    int failed;
    int i;

    ps3_log("core:  running ports/common's suites on this hardware\n");

    /* Redirected, not duplicated: there is no dup2 to restore through here, and rc_log still reaches
     * its own file and the network, so nothing is actually lost by giving stdout away. */
    if (freopen(RC_CORE_TEST_CAPTURE, "w", stdout) == NULL)
        ps3_log("      (stdout could not be captured - the runners' detail will be lost)\n");

    failed = rc_core_tests_run(results);

    fflush(stdout);

    for (i = 0; i < RC_CORE_TEST_COUNT; i++)
        ps3_log("       %-14s %s\n", results[i].name,
                results[i].skipped ? "skipped - no vectors on this console"
                                   : (results[i].exit_code == 0 ? "pass" : "FAIL"));

    for (i = 0; i < RC_CORE_TEST_COUNT; i++)
        if (results[i].skipped) {
            ps3_log("       (copy ports/common/tests/vectors/*.kat to %s to run those)\n",
                    RC_CORE_TEST_VECTOR_DIR);
            break;
        }

    if (failed != 0) {
        ps3_log("FAIL  %d of %d core suites failed on big-endian - their output follows\n",
                failed, RC_CORE_TEST_COUNT);
        replay_captured(RC_CORE_TEST_CAPTURE);
        return 1;
    }

    {
        int ran = 0;
        for (i = 0; i < RC_CORE_TEST_COUNT; i++)
            if (!results[i].skipped)
                ran++;
        ps3_log("ok    %d of %d core suites pass on the PPE - the shared core is byte-order clean\n",
                ran, RC_CORE_TEST_COUNT);
    }
    return 0;
}

/*
 * THE FIRST THING IN THIS PORT THAT TALKS TO A PS5. Everything else has been checked against vectors,
 * captures and reference decodes, all of which are recordings - and a recording cannot refuse a
 * datagram, answer from an address you did not expect, or take longer than you allowed.
 *
 * A console that is off, resting, or on another subnet is not a failure of this program, so finding
 * nothing is reported and not counted against the run. What IS reported either way is how far the
 * socket work got, because "no console answered" and "this port cannot broadcast" look identical from
 * the outside and are entirely different problems.
 */
#ifndef RC_DISCOVER_TIMEOUT_MS
#define RC_DISCOVER_TIMEOUT_MS 3000u
#endif

static int check_discovery(void)
{
    rc_discover_result d;
    int n;
    int i;

    ps3_log("disc:  broadcasting SRCH for %u ms\n", RC_DISCOVER_TIMEOUT_MS);

    n = rc_discover(RC_DISCOVER_TIMEOUT_MS, &d);

    /* The [X] rc_platform.h left open, asked and answered on hardware. Reported whatever discovery
     * found, because it is a fact about the platform rather than about the network. */
    ps3_log("       bind() to port 0: %s%s\n",
            d.bind_port0_ok ? "accepted" : "REFUSED",
            d.bind_port0_ok ? " - the 3DS's restriction does not apply here"
                            : " - fell back to the discovery port");
    if (!d.bind_port0_ok)
        ps3_log("       (errno %d)\n", d.bind_errno);

    /*
     * Whether sin_len is required, which decides whether ports/common needs a change. It builds
     * sockaddr_in in three places and never sets the field, so this is a question about the shared core
     * rather than about this port.
     */
    ps3_log("       sendto with sin_len=0: %s;  with sin_len set: %s\n",
            d.sinlen_zero_send_ok ? "accepted" : "REFUSED",
            d.sinlen_set_send_ok ? "accepted" : "REFUSED");
    if (!d.sinlen_zero_send_ok && d.sinlen_set_send_ok)
        ps3_log("       -> sin_len IS required. ports/common must set it before it can connect here.\n");
    else if (d.sinlen_zero_send_ok)
        ps3_log("       -> sin_len is not required for sendto. ports/common needs no change for this.\n");

    if (!d.socket_ok) {
        ps3_log("FAIL  could not create or configure the broadcast socket\n");
        return 1;
    }
    if (d.probes_sent == 0) {
        ps3_log("FAIL  the socket came up but the SRCH broadcast could not be sent\n");
        return 1;
    }

    ps3_log("       sent %d probe(s), %d datagram(s) back, %d parsed\n",
            d.probes_sent, d.datagrams_rx, d.parsed);

    if (n == 0) {
        ps3_log("       no console answered - not a failure; check it is on the same LAN and awake\n");
        return 0;
    }

    for (i = 0; i < n; i++)
        ps3_log("       %s  %s  %s  id=%s  sysver=%s  %s\n",
                d.console[i].address, d.console[i].host_type, d.console[i].host_name,
                d.console[i].host_id, d.console[i].system_version,
                d.console[i].is_awake ? "awake" : "standby");

    ps3_log("ok    found %d console(s) from the PS3 - discovery works end to end\n", n);
    return 0;
}

/*
 * Wake the console and open the control session. Needs a pairing record, which is dirty-room material -
 * see rc_connect.h. NOTHING BELOW PRINTS ANYTHING FROM IT: not the keys, not the derived credential, not
 * the host address. What it reports is which stage was reached, which is the useful part anyway.
 */
#ifndef RC_CONNECT_WAKE_TIMEOUT_MS
#define RC_CONNECT_WAKE_TIMEOUT_MS 30000u
#endif

/* Printed the moment rc_connect enters a step that can block, so a hang names the call that did not
 * return rather than leaving the log stopping after the previous check. */
static void connect_progress(const char *stage_text)
{
    ps3_log("       .. %s\n", stage_text);
}

/*
 * Bytes as hex. TAKES A COUNT, because b156 printed sixteen bytes from the eight-byte diff arrays and
 * the overrun read adjacent struct memory - which happened to look like an Annex-B start code and very
 * nearly got read as data.
 */
static void log_bytes(const char *label, const uint8_t *bytes, int count)
{
    char line[80];
    int i;

    if (count > 16)
        count = 16;
    for (i = 0; i < count; i++)
        (void)snprintf(line + i * 3, sizeof(line) - (size_t)(i * 3), "%02x ", bytes[i]);
    line[count * 3] = '\0';
    ps3_log("         %s %s\n", label, line);
}

/* Set from the connect result, since the live decoder is closed by the time this stage runs. */
static int g_live_backend_id;

static int check_connect(void)
{
    rc_connect_result c;
    rc_connect_stage stage;

    ps3_log("conn:  starting\n");
    stage = rc_connect(RC_CONNECT_WAKE_TIMEOUT_MS, connect_progress, g_log_dirs, LOG_DIR_COUNT, &c);

    if (stage == RC_CONNECT_NO_RECORD) {
        ps3_log("conn:  no pairing record - skipping\n");
        ps3_log("       generate one with `ProtocolLab -- register`, copy it to the console as\n");
        ps3_log("       pairing.txt - that exact name, which is what the core's loader appends;\n");
        ps3_log("       it is per-console and per-account, so it never belongs in this repository.\n");
        ps3_log("       every directory listed in the writable-directory probe above was searched,\n");
        ps3_log("       so any of them will do - the install directory is the one tried first.\n");
        return 0;
    }

    /*
     * Only claims what was observed. An earlier version printed "console was awake" off a flag that was
     * still at its memset default when nothing had answered at all - which read as a successful probe
     * immediately above a line saying no console answered.
     */
    ps3_log("conn:  record loaded from %s; recorded address %s\n",
            c.record_dir != NULL ? c.record_dir : "the compiled-in directory",
            c.host_parsed ? "parses" : "IS NOT A DOTTED QUAD");
    ps3_log("       fcntl(F_SETFL,O_NONBLOCK)=%d, reads back non-blocking: %s; SO_NBIO: %s\n",
            c.fcntl_set_rc,
            c.fcntl_readback_nonblock ? "yes" : "NO - sockets are not newlib fds here",
            c.so_nbio_ok ? "accepted" : "refused");
    ps3_log("       inet_pton: %s   inet_aton: %s   agree: %s\n",
            c.pton_ok ? "ok" : "FAILED",
            c.aton_ok ? "ok" : "FAILED",
            c.aton_matches_pton ? "yes" : "NO - the core uses inet_aton everywhere");

    /*
     * THE SENKUSHA MEASUREMENTS, printed here rather than inside a stage's case.
     *
     * They first went into the STREAM_KEYS case, which since sealing landed is the FAILURE path - a
     * successful run reaches STREAM_READY and skipped them entirely, so b119 took the measurements and
     * reported none of them. The same mistake as putting the SPE init after the stage that needed it:
     * placed where the text read well rather than where control flow goes.
     *
     * These happen early and matter whatever stage is reached afterwards, so they belong with the other
     * unconditional lines above.
     */
    if (c.senkusha_complete) {
        ps3_log("       senkusha echo: %u/%u echoes, handshake round trip %d ms\n",
                c.echo_samples, 10u, c.handshake_rtt_ms);
        ps3_log("       declared rtt %d ms (%s), mtu %d (%s)\n",
                c.measured_rtt_ms,
                c.measured_rtt_ms == 0 ? "nothing measured"
                                       : (c.rtt_from_echo ? "from the echo probe"
                                                          : "handshake fallback - the echo probe did"
                                                            " NOT get a majority"),
                c.measured_mtu > 0 ? c.measured_mtu : 1454,
                (c.measured_mtu > 0) ? "confirmed both directions"
                                     : (c.mtu_downstream ? "downstream only - declared anyway"
                                                         : "unconfirmed - declared anyway"));
    }

    if (c.unicast_replied)
        ps3_log("       it answered; %s\n", c.was_asleep ? "in standby" : "awake");
    else if (c.broadcast_found && !c.broadcast_matches)
        ps3_log("       it did not answer, but a console answered a BROADCAST from a different\n"
                "       address - the record is stale, not the console missing. Re-register, or\n"
                "       give the console a reservation so its address stops moving.\n");
    else if (c.broadcast_found)
        ps3_log("       it did not answer a unicast SRCH, yet the same address answered a\n"
                "       broadcast - suspect the source port this binds, not the address.\n");
    else
        ps3_log("       nothing answered, unicast or broadcast - console off, or another subnet\n");

    if (c.wakeups_sent > 0) {
        ps3_log("       wake credential derived: %s\n", c.credential_ok ? "yes" : "NO");
        ps3_log("       WAKEUP sent from %s source port\n",
                c.wake_source_bound ? "the spec's" : "an ephemeral");
        if (stage != RC_CONNECT_WAKE_SENT)
            ps3_log("       woke after %u ms (%d SRCH polls)\n", c.woke_after_ms, c.polls);
    }

    ps3_log("       stage reached: %s\n", rc_connect_stage_name(stage));

    switch (stage) {
    case RC_CONNECT_STREAM_READY:
        if (c.login_verdict == 0)
            ps3_log("       the console accepted the passcode (LOGIN 0x0005 -> 0x00)\n");
        ps3_log("       protocol version %u, curve %s, SESSION_REPLY %u bytes\n",
                c.stream_version, c.curve_p521 ? "P-521" : "P-256", c.session_reply_bytes);
        ps3_log("       GMAC sealing on - every control packet from here, SACKs included\n");
        ps3_log("       incoming tags: %lu checked, %lu failed (ENFORCING - failures are dropped)\n",
                c.verify_checked, c.verify_failed);
        if (c.verify_checked == 0UL)
            ps3_log("       nothing arrived to check - the sample says nothing either way\n");
        else if (c.verify_failed == 0UL)
            ps3_log("       every one verified. A 32-bit tag passing by chance is ~1 in 4e9, so the\n"
                    "       RECEIVE SCHEDULE is right; whether ALL console traffic is sealed is a\n"
                    "       separate question and wants the sample size above to be large.\n");
        else
            ps3_log("       %lu failed - if that is all of them the receive key schedule is wrong;\n"
                    "       if it is a few, some traffic is not sealed the way this assumes.\n",
                    c.verify_failed);
        if (c.verify_dropped > 0UL)
            ps3_log("       %lu packet(s) DROPPED for failing authentication\n", c.verify_dropped);
        ps3_log("       sent %u heartbeat(s) and %u congestion report(s) on the stream channel\n",
                c.heartbeats_sent, c.congestion_sent);
        ps3_log("       A/V on the same socket: %u packet(s), %lu bytes - %u video, %u audio, %u other\n",
                c.av_packets, c.av_bytes, c.av_video, c.av_audio, c.av_other);
        if (c.av_packets > 0u)
            ps3_log("       %u of %u handed to the demuxer, which authenticates them under the A/V rule\n"
                    "       (tag@10, key pos from the packet at @14, only the tag zeroed - not control's).\n"
                    "       The units received/lost below are its verdict; this loop no longer verifies\n"
                    "       a second time, which cost a GMAC per packet on the thread draining the socket.\n",
                    c.av_ingested, c.av_packets);
        else
            ps3_log("       none arrived. Until now poll's recvfrom consumed and discarded them, so\n"
                    "       'no A/V' and 'A/V thrown away' looked identical - this run can tell them apart.\n");
        if (c.demux_ready) {
            ps3_log("       demux: %u video frame(s) (%u keyframe(s), %lu bytes, largest %u),"
                    " %u audio frame(s) (%lu bytes)\n",
                    c.video_frames, c.keyframes, c.video_frame_bytes, c.largest_frame,
                    c.audio_frames, c.audio_frame_bytes);
            ps3_log("       receive buffer: asked %d, platform says %d%s\n",
                    c.stream_rcvbuf_asked, c.stream_rcvbuf,
                    (c.stream_rcvbuf > 0 && c.stream_rcvbuf < c.stream_rcvbuf_asked)
                        ? "  <- CAPPED. A buffer smaller than a burst loses its tail, and that"
                          " looks exactly like the network."
                        : (c.stream_rcvbuf == 0 ? "  (the platform declined to say)" : ""));
            ps3_log("       worst drain burst %u of %u%s\n", c.av_worst_burst, RC_AV_DRAIN_BURST,
                    (c.av_worst_burst >= RC_AV_DRAIN_BURST)
                        ? " - AT THE BOUND. Benign at this rate: yielding every 64 packets is every"
                          " ~300 ms, and the heartbeat it protects is every 1000 ms. Worth watching if"
                          " the bitrate rises."
                        : "");
            ps3_log("       units %ld received, %ld lost; %u loss event(s), %u IDR requested\n",
                    c.units_received, c.units_lost, c.corrupt_events, c.idr_requests);
            if (c.corrupt_events > 0u && c.keyframes <= 1u && c.idr_requests == 0u)
                ps3_log("       loss with no IDR requested - every frame after the gap is undecodable\n");
            if (c.decoded_fed > 0) {
                unsigned long hz = (unsigned long)rc_tick_hz();
                /*
                 * PER FRAME FED, not per picture produced.
                 *
                 * This divided by decoded_pictures, which is right only when every frame decodes. On a
                 * run with 702 frames and 330 pictures it reported 40221 us and the true cost per decode
                 * call was 18907 - it looked as though real content had made decoding twice as expensive,
                 * when decoding had not changed at all and the failures were the story.
                 */
                unsigned long us = (hz > 0UL && c.decoded_fed > 0)
                    ? (unsigned long)((c.decode_ticks * 1000000ULL) / hz) / (unsigned long)c.decoded_fed
                    : 0UL;

                ps3_log("       DECODED LIVE: %d picture(s) from %d frame(s) at %dx%d, %d error(s)\n",
                        c.decoded_pictures, c.decoded_fed, c.decoded_width, c.decoded_height,
                        c.decoded_errors);
                if (us > 0UL)
                    ps3_log("       %lu us per decode call on the PPE (%d fed, %d produced) -"
                            " the budget at 30 fps is 33333 us\n",
                            us, c.decoded_fed, c.decoded_pictures);
                if (c.blits > 0u) {
                    ps3_log("       scaled to %dx%d on a %dx%d display\n",
                            c.scaled_width, c.scaled_height, c.display_width, c.display_height);
                    ps3_log("       ON SCREEN: %u picture(s) blitted, %u us average, %u us worst;"
                            " %u dropped because the display was busy\n",
                            c.blits, c.blit_avg_us, c.blit_worst_us, c.pictures_dropped);
                    ps3_log("       longest gap between socket reads: %u ms"
                            " (a 122 KB buffer at this rate fills in ~400 ms)\n",
                            c.worst_read_gap_ms);
                    ps3_log("       worst phase: drain %u ms, decode run %u ms, everything else %u ms\n",
                            c.worst_drain_ms, c.worst_decode_ms, c.worst_other_ms);
                    ps3_log("       frame queue: %u queued, %u dropped for overrun, deepest %u of 8\n",
                            c.frames_queued, c.frames_overrun, c.queue_worst);
                    ps3_log("       decode + blit is %lu us against the same 33333 us budget\n",
                            us + (unsigned long)c.blit_avg_us);
                    if (c.hold_ms > 0u)
                        ps3_log("       %u pictures over %u ms = %u fps on screen\n",
                                c.blits, c.hold_ms, (c.blits * 1000u) / c.hold_ms);
                } else {
                    /*
                     * SAY WHAT IS KNOWN, NOT WHY. This branch used to claim "the display was not open",
                     * which is a cause nobody here checked - in b141 the display was open and had just
                     * drawn the test pattern, and the real reason was that the decoder produced no
                     * pictures to blit. An over-confident diagnostic stops the next person looking.
                     */
                    ps3_log("       nothing reached the screen - %u picture(s) were available to blit\n",
                            c.decoded_pictures);
                }
                /*
                 * Outside the block above on purpose: this measures the RECEIVE path, which runs whether
                 * or not anything ever reached the screen. b141 decoded nothing, and so hid the one
                 * number that would have confirmed the crypto rewrite from the live path.
                 */
                if (c.decode_level > 0)
                    ps3_log("       opened at H.264 level %d, reserving %u bytes;"
                            " the stream's own SPS says level %d\n",
                            c.decode_level, c.decode_mem_size,
                            (c.first_au_len >= 8u) ? (int)c.first_au[7] : 0);
                if (!c.audio_ready) {
                    ps3_log("       AUDIO NOT RUNNING (error %d) - the stream played without it\n",
                            c.audio_last_error);
                } else {
                    ps3_log("       audio: %u frame(s) decoded, %u error(s); %u block(s) to the"
                            " hardware\n",
                            c.audio_frames_decoded, c.audio_decode_errors, c.audio_blocks);
                    ps3_log("       %u block(s) were SILENCE - the ring ran dry, which is the one"
                            " fault a listener hears\n", c.audio_silence);
                    ps3_log("       ring reached %u of %d samples; %u dropped to overflow;"
                            " readIndex is %s\n",
                            c.audio_worst_ring, RC_AUDIO_RING_SAMPLES, c.audio_overflows,
                            c.audio_index_is_address ? "an ADDRESS" : "an index");
                }
                ps3_log("       decoded by %s\n",
                        (c.decode_backend != NULL) ? c.decode_backend : "?");
                if (c.decoded_pictures > 0) {
                    ps3_log("       delivered luma ranged %d..%d\n", c.luma_min, c.luma_max);
                    ps3_log("       the decoder's own thread saw a peak of %d over %d picture(s)"
                            " right after writing them\n",
                            c.callback_luma_max, c.callback_pictures);
                    ps3_log("       pictures were written to 0x%08X (%s128-byte aligned)\n",
                            c.picture_addr, (c.picture_addr & 127u) == 0u ? "" : "NOT ");
                    if (c.first_au_len > 0u) {
                        log_bytes("first AU", c.first_au, 8);
                        ps3_log("         (%u bytes; Annex-B begins 00 00 00 01 or 00 00 01)\n",
                                c.first_au_len);
                    }
                    if (c.luma_max == 0 && c.callback_luma_max > 0)
                        ps3_log("       WRITTEN BUT NOT SEEN: the decoder filled the buffer and the\n"
                                "       reading thread found zeros. That is visibility, not decoding.\n");
                    else if (c.luma_max == 0)
                        ps3_log("       ALL ZERO - the pictures handed to the screen were black, which\n"
                                "       is what b160's 431 successful blits actually blitted.\n");
                }
                g_live_backend_id = c.decode_backend_id;
                ps3_log("       decode ran on its own thread at priority %d;"
                        " the receive loop is %d\n",
                        c.decode_thread_priority, c.decode_receive_priority);
                if (c.decode_thread_failed)
                    ps3_log("       WARNING: the decoder thread would not start - decode did not run\n");
                ps3_log("       demux ingest: %u us per packet, of which crypto is %u us"
                        " and everything else %u us\n",
                        c.ingest_avg_us, c.crypto_avg_us,
                        (c.ingest_avg_us > c.crypto_avg_us)
                            ? c.ingest_avg_us - c.crypto_avg_us : 0u);
                if (c.decoded_errors > 0)
                    ps3_log("       last decoder error 0x%x\n", (unsigned)c.decoded_last_error);
                if (c.decoded_pictures < c.decoded_fed)
                    ps3_log("       fewer pictures than frames is normal at the start - the decoder\n"
                            "       produces nothing until its first keyframe\n");
            }
            if (c.video_frames > 0u && c.keyframes == 0u)
                ps3_log("       NO KEYFRAME yet - a stream no decoder can start on, which is not the\n"
                        "       same finding as no frames at all\n");
        } else {
            ps3_log("       demux was never started - no video header to start it with\n");
        }
        ps3_log("       held the session %u ms: %u message(s), last type 0x%04x%s\n",
                c.hold_ms, c.held_messages, c.held_last_type,
                c.held_channel_error ? ", CHANNEL ERROR" : "");
        if (c.held_stream_info_repeats > 0u)
            ps3_log("       the console re-sent STREAM_INFO %u time(s) - it did not hear an ack\n",
                    c.held_stream_info_repeats);
        ps3_log("       STREAM_INFO %u bytes, acked: asked %dx%d, GIVEN %dx%d\n",
                c.stream_info_bytes, c.asked_width, c.asked_height, c.given_width, c.given_height);
        ps3_log("       %u-byte video header (SPS/PPS), %u-byte audio header\n",
                c.video_header_bytes, c.audio_header_bytes);
        if (c.given_width != c.asked_width || c.given_height != c.asked_height)
            ps3_log("       the console chose a different resolution than requested - its choice wins\n");
        ps3_log("ok    the console has described the stream and is ready to send it\n");
        return 0;
    case RC_CONNECT_STREAM_KEYS:
        if (c.login_verdict == 0)
            ps3_log("       the console accepted the passcode (LOGIN 0x0005 -> 0x00)\n");
        ps3_log("       senkusha  local 0x%08x  peer 0x%08x  version-ack %s, gating legs %s\n",
                c.senkusha_local_tag, c.senkusha_peer_tag,
                c.senkusha_version_ack ? "yes" : "NO", c.senkusha_complete ? "complete" : "INCOMPLETE");
        ps3_log("       stream    local 0x%08x  peer 0x%08x\n",
                c.takion_local_tag, c.takion_peer_tag);
        ps3_log("       protocol version %u (%s), so the curve is %s\n",
                c.stream_version, c.stream_version_acked ? "the console's choice" : "ours - no ack",
                c.curve_p521 ? "P-521" : "P-256");
        ps3_log("       SESSION_REQUEST %u bytes, SESSION_REPLY %u bytes\n",
                c.session_request_bytes, c.session_reply_bytes);
        ps3_log("       the reply's ECDH point verified under the handshake key - that signature\n");
        ps3_log("       check is what stops an injected DATA chunk substituting its own key.\n");
        ps3_log("       GMAC sealing: %s\n", c.sealing_on ? "on" : "NOT ARMED");
        if (c.stream_info_bytes > 0u)
            ps3_log("       STREAM_INFO arrived (%u bytes) but was not acked\n", c.stream_info_bytes);
        else
            ps3_log("       no STREAM_INFO within the wait - the console has not described the stream\n");
        ps3_log("FAIL  keys derived, but the console never got to describing the stream\n");
        return 1;
    case RC_CONNECT_TAKION_UP:
        if (c.login_verdict == 0)
            ps3_log("       the console accepted the passcode (LOGIN 0x0005 -> 0x00)\n");
        ps3_log("       senkusha  local 0x%08x  peer 0x%08x\n",
                c.senkusha_local_tag, c.senkusha_peer_tag);
        ps3_log("       stream    local 0x%08x  peer 0x%08x\n",
                c.takion_local_tag, c.takion_peer_tag);
        ps3_log("       senkusha gating legs: version-ack %s, keyless session %s\n",
                c.senkusha_version_ack ? "yes" : "NO", c.senkusha_complete ? "complete" : "INCOMPLETE");
        ps3_log("FAIL  Takion is up on both channels but the stream SESSION exchange did not finish.\n");
        if (c.session_reply_bytes > 0u) {
            static const char *const kReject[] = {
                "no reason recorded - which should not happen here",
                "bad arguments - a bug on this side, not the console's",
                "it did not parse as a SESSION_REPLY at all",
                "the console REFUSED OUR PROTOCOL VERSION",
                "version accepted, but the reply carried no ECDH key",
                "the ecdhSignature was not 32 bytes",
                "the ecdhSignature DID NOT VERIFY under our handshake key - the console computed"
                " it under a different one, which points at the launch spec's encryption",
                "the console's point LENGTH names a different curve than the one we used",
                "the length agreed and the derivation still failed - this is the crypto, not"
                " the negotiation"
            };
            int why = c.reply_reject_reason;

            ps3_log("      the console's point: %u bytes, first byte 0x%02x"
                    " (65 = P-256, 133 = P-521, 0x04 = uncompressed)\n",
                    c.peer_key_length, c.peer_key_prefix);
            ps3_log("      protocol version %u (%s), curve %s\n",
                    c.stream_version, c.stream_version_acked ? "the console's choice" : "ours - no ack",
                    c.curve_p521 ? "P-521" : "P-256");

            ps3_log("      A SESSION_REPLY of %u bytes DID arrive and was refused - so the console\n",
                    c.session_reply_bytes);
            ps3_log("      answered and we declined it, which is not the same as silence.\n");
            if (why >= 0 && why < (int)(sizeof(kReject) / sizeof(kReject[0])))
                ps3_log("      %s\n", kReject[why]);
            if (c.ecdh_step != 0) {
                static const char *const kEcdhStep[] = {
                    "none", "arguments", "curve", "sizes", "group load", "our private key",
                    "reading the peer point", "checking the peer point",
                    "THE POINT MULTIPLY", "the result was the identity", "writing the result"
                };
                int st = c.ecdh_step;

                ps3_log("      backend step %d (%s), code %d (0x%04x)\n", st,
                        (st >= 0 && st < (int)(sizeof(kEcdhStep) / sizeof(kEcdhStep[0])))
                            ? kEcdhStep[st] : "?",
                        c.ecdh_code, (unsigned)(-c.ecdh_code));
                ps3_log("      the code is mbedtls's own and unmapped - -0x4c80 is INVALID_KEY,\n");
                ps3_log("      -0x4d80 is ALLOC_FAILED.\n");
            }
            if (c.peer_key_length > 0u && c.peer_key_length <= sizeof(c.peer_key)) {
                /*
                 * The point itself. An ephemeral public key for one session - no secret, no account, no
                 * console identity - printed so it can be checked off the console, because the four
                 * P-521 vectors sitting on this machine pass the check this point fails.
                 */
                unsigned i;

                ps3_log("      control: a known-good P-521 vector point %s here; the console's %s\n",
                        c.control_point_ok ? "PASSES" : "FAILS",
                        c.peer_point_ok ? "PASSES" : "FAILS");
                if (!c.control_point_ok)
                    ps3_log("      control failed at step %d code %d - so this is the call site, not the key\n",
                            c.control_step, c.control_code);
                ps3_log("      stack: %lu bytes given, %lu used here, %lu left\n",
                        c.stack_size, c.stack_used, c.stack_headroom);
                ps3_log("      the SAME check run one call earlier, same heap and depth: %s%s\n",
                        c.precheck_ok ? "PASSES" : "FAILS",
                        c.precheck_ok
                            ? " -> the subject is inside the derivation's own frame"
                            : " -> the subject is the environment at that moment");
                if (!c.precheck_ok)
                    ps3_log("      (precheck step %d code %d)\n", c.precheck_step, c.precheck_code);
                ps3_log("      derive saw fingerprint %08lx, the copy is %08lx - %s\n",
                        c.derive_fingerprint, c.copy_fingerprint,
                        (c.derive_fingerprint == c.copy_fingerprint)
                            ? "SAME BYTES, so the difference is the call, not the data"
                            : "DIFFERENT BYTES - the pointer went stale under the derivation");
                ps3_log("      derive's view: curve %u, our private key %u bytes\n",
                        c.derive_curve, c.derive_private_length);
                ps3_log("      peer point, for off-console analysis:\n      ");
                for (i = 0u; i < c.peer_key_length; i++) {
                    ps3_log("%02x", c.peer_key[i]);
                    if (((i + 1u) % 32u) == 0u && (i + 1u) < c.peer_key_length)
                        ps3_log("\n      ");
                }
                ps3_log("\n");
            }
        } else if (c.session_request_bytes > 0u) {
            ps3_log("      SESSION_REQUEST went out (%u bytes, %s) and nothing came back. If the\n",
                    c.session_request_bytes, c.curve_p521 ? "P-521" : "P-256");
            ps3_log("      senkusha gating legs above are incomplete, suspect those first.\n");
        } else {
            /*
             * Name the step that failed rather than the set of candidates. The same sequence with the
             * same parameters and buffers succeeds on the host, so "one of these three" was never going
             * to be enough to act on.
             */
            static const char *const kStep[] = {
                "the handshake key could not be drawn - the CSPRNG refused 16 bytes",
                "the launch spec JSON would not build (resolution ladder, or the buffer)",
                "the launch spec would not encrypt-and-base64",
                "SESSION_REQUEST would not build - this is the ECDH keygen",
                "SESSION_REQUEST was built but the channel refused to send it",
                "SESSION_REQUEST went out and no SESSION_REPLY came back"
            };
            int step = c.stream_build_step;

            ps3_log("      spec %u bytes, base64 %u bytes, step reached %d\n",
                    c.launch_spec_bytes, c.launch_spec_b64_bytes, step);
            if (step >= 0 && step < (int)(sizeof(kStep) / sizeof(kStep[0])))
                ps3_log("      %s\n", kStep[step]);
        }
        return 1;
    case RC_CONNECT_SENKUSHA_UP:
        ps3_log("       senkusha  local 0x%08x  peer 0x%08x\n",
                c.senkusha_local_tag, c.senkusha_peer_tag);
        ps3_log("FAIL  senkusha came up but the stream channel's Takion handshake did not. The\n");
        ps3_log("      console answered on one UDP port and not the other, which is a different\n");
        ps3_log("      problem from never answering at all.\n");
        return 1;
    case RC_CONNECT_SESSION_READY:
        if (c.login_verdict == 0)
            ps3_log("       the console accepted the passcode (LOGIN 0x0005 -> 0x00)\n");
        ps3_log("FAIL  the console is willing to stream but senkusha's Takion handshake never\n");
        ps3_log("      completed - no INIT_ACK. The control plane is healthy, so this is the UDP\n");
        ps3_log("      leg specifically.\n");
        return 1;
    case RC_CONNECT_SESSION_OPEN:
        ps3_log("       %d control frame(s) while waiting; first 0x%04x, last 0x%04x, %d heartbeat(s)\n",
                c.frames_seen, c.first_type, c.last_type, c.heartbeats);
        if (c.login_prompt && c.login_verdict == 1) {
            ps3_log("FAIL  the console REJECTED the passcode in the pairing record. That is its own\n");
            ps3_log("      answer, not a timeout - correct `pin=` and re-run.\n");
        } else if (c.login_prompt && c.login_verdict == 2) {
            ps3_log("FAIL  the console answered the passcode with a verdict byte nobody has seen\n");
            ps3_log("      before - neither 0x00 nor 0x01. Worth a look rather than a retry.\n");
        } else if (c.login_prompt && c.login_verdict == 0) {
            ps3_log("FAIL  the console ACCEPTED the passcode and then sent no SESSION_ID within the\n");
            ps3_log("      deadline. The reference sees session-ready ~2.3 s after a LAN submit, so\n");
            ps3_log("      this is the console being slow or the session stalling after login - it\n");
            ps3_log("      is NOT a bad passcode.\n");
        } else if (c.login_prompt && c.login_submitted) {
            ps3_log("FAIL  the passcode went back to the console and nothing returned - no verdict,\n");
            ps3_log("      no SESSION_ID. The console went quiet rather than saying no.\n");
        } else if (c.login_prompt) {
            ps3_log("       the console wants a sign-in passcode and none was supplied. Either put\n");
            ps3_log("       `pin=<digits>` in the pairing record beside the console, or sign in on\n");
            ps3_log("       the console, leave it on the home screen, and re-run.\n");
        } else if (c.frames_seen == 0) {
            ps3_log("FAIL  the channel opened and the console said nothing at all - not even a\n");
            ps3_log("      heartbeat, which it normally sends within seconds. Suspect the channel.\n");
        } else {
            ps3_log("FAIL  the channel is live (frames arriving) but no SESSION_ID in 20 s\n");
        }
        return 1;
    case RC_CONNECT_AWAKE:
        ps3_log("FAIL  console is awake but the control session would not open\n");
        return 1;
    case RC_CONNECT_WAKE_SENT:
        ps3_log("FAIL  it did not wake within %u ms\n", RC_CONNECT_WAKE_TIMEOUT_MS);
        return 1;
    default:
        ps3_log("FAIL  %s\n", rc_connect_stage_name(stage));
        return 1;
    }
}

/*
 * WHAT THIS MEASURES AND WHY IT IS A STAGE RATHER THAN A NOTE.
 *
 * b140 split the demuxer's 829 us per packet into "crypto 837 us, everything else 11 us", which named the
 * cipher as the cost but not the reason for it. The reason turned out to be the shape of the code rather
 * than the amount of arithmetic: both AES and GHASH kept their state in a `uint8_t[16]` on the stack, and
 * the PPE is in-order, so every step stored a byte and the next step stalled reloading it. Both now keep
 * their state in 32-bit registers (see rc_aes.c and rc_gcm.h).
 *
 * This stage times the primitives directly so the next build's number is attributable to them and not
 * inferred from a live stream, where loss, decode and scheduling all move at once. The per-packet line at
 * the end is the quantity that actually matters: one GMAC plus one CTR pass over a full-MTU packet, which
 * is exactly what the demuxer's crypto seam does per A/V packet.
 *
 * It is a measurement, not a correctness test - but it opens with FIPS-197 C.1 anyway, because a word
 * rewrite is exactly the kind of change that a big-endian toolchain could break in a way the host suite
 * (little-endian) would never see.
 */
#define RC_CRYPTO_BENCH_PACKET 1400
#define RC_CRYPTO_BENCH_BLOCKS 2000
#define RC_CRYPTO_BENCH_PASSES 200

static unsigned bench_us(uint64_t ticks, uint64_t hz, unsigned iterations)
{
    if (hz == 0u || iterations == 0u)
        return 0u;
    return (unsigned)((ticks * 1000000u) / hz / iterations);
}

static unsigned bench_ns(uint64_t ticks, uint64_t hz, unsigned iterations)
{
    if (hz == 0u || iterations == 0u)
        return 0u;
    return (unsigned)((ticks * 1000000000u) / hz / iterations);
}

/*
 * Does this console expose its own H.264 decoder, and on what terms?
 *
 * b144 made the case for asking: with the receive path finally clean the console tripled its bitrate,
 * and openh264 on the PPE went from ~37 ms per successful decode to somewhere near 70-83 ms, which is a
 * 12-14 fps ceiling on a 30 fps stream. cellVdec runs on the SPEs instead.
 *
 * vdecType.profile_level has no constant in any SDK header, so this sweeps it rather than guessing -
 * see rc_vdec_probe.h. The output is the set the console accepts and what each wants for memory, which
 * is what the real implementation needs before it can be written honestly.
 */

/* openh264's first-picture plane hashes, kept so check_vdec can identify the other decoder's layout by
 * reproducing them. check_decode runs first; see the stage list at the foot of main(). */
static uint64_t s_reference_hash_y;
static uint64_t s_reference_hash_u;

static void vdec_step_log(const char *message)
{
    ps3_log("%s\n", message);
}

static int check_vdec(void)
{
    rc_vdec_probe_result v;

    if (!rc_vdec_probe(&v)) {
        ps3_log("vdec:  SYSMODULE_VDEC_H264 did not load (0x%08X)\n", (unsigned)v.module_load);
        ps3_log("       not a failure of this build - it means the hardware decoder is not reachable\n"
                "       this way, and the PPE decoder stays the only path.\n");
        return 0;
    }

    ps3_log("vdec:  module loaded; swept %d profile_level value(s)\n", v.queried);
    if (v.accepted == 0) {
        ps3_log("       NONE accepted. Last rejection was 0x%08X.\n", (unsigned)v.last_error);
        ps3_log("       the sweep is the derivation, so this says the value is not a plain 0..255 -\n"
                "       it is packed, or the query wants something else set first.\n");
        return 0;
    }

    ps3_log("       %d accepted, from %d to %d\n", v.accepted, v.first_accepted, v.last_accepted);
    ps3_log("       lowest accepted (%d): %u bytes, cmd depth %u, version %u.%u\n",
            v.first_accepted, v.first_mem_size, v.cmd_depth, v.ver_major, v.ver_minor);
    ps3_log("       largest appetite: %u bytes at level %d\n",
            v.largest_mem_size, v.largest_mem_level);
    ps3_log("       a 1280x720 YUV420 picture is %d bytes, for comparison\n", 1280 * 720 * 3 / 2);
    {
        int i;

        ps3_log("       accepted:");
        for (i = 0; i < v.level_count; i++)
            ps3_log(" %d", v.levels[i]);
        ps3_log("\n");
        ps3_log("       H.264's own level_idc set is 10 11 12 13 20 21 22 30 31 32 40 41 42 -\n"
                "       if those match, profile_level IS level_idc and this is derived, not assumed.\n");
    }

    /*
     * AND NOW THE ONLY QUESTION THAT MATTERS: does it decode the same bytes into the same pictures?
     * Offline, against the same capture openh264 decodes above, hashed by the same function. The live
     * path is untouched by this - a failure here costs a run, not a session.
     */
    {
        rc_vdec_decode_result d;
        int decoded;

        if (g_live_backend_id == (int)RC_DECODE_BACKEND_VDEC) {
            ps3_log("vdec:  the live path used this decoder, so the offline check is skipped -\n"
                    "       opening a second instance would prove nothing and could fail for that\n"
                    "       reason alone. b159 is the run that validated it: Y, U and V bit-identical\n"
                    "       to openh264, and its luma identical to ffmpeg's on the host as well.\n");
            return 0;
        }
        ps3_log("vdec:  the live path did NOT use this decoder - running the offline check to say why\n");
        ps3_log("vdec:  decoding %s with the console's decoder at level 31\n", RC_DECODE_STREAM_PATH);
        decoded = rc_vdec_decode_probe(RC_DECODE_STREAM_PATH, 31, RC_DECODE_PROBE_FRAMES,
                                       vdec_step_log, s_reference_hash_y, s_reference_hash_u, &d);

        ps3_log("       reached step %d (see rc_vdec_step), wanted %u bytes of decoder memory\n",
                d.last_step, d.mem_size);
        if (!decoded) {
            ps3_log("       NO PICTURES. opened=%d, aus fed=%d, last error 0x%08X\n",
                    d.opened, d.aus_fed, (unsigned)d.last_error);
            ps3_log("       the step number says how far it got; every [X] in rc_vdec_probe.c is a\n"
                    "       candidate, and the open/start ones fail loudly rather than subtly.\n");
            return 0;
        }

        ps3_log("       %d picture(s) from %d access unit(s) at %dx%d\n",
                d.pictures_out, d.aus_fed, d.width, d.height);
        {
            uint64_t hz = rc_tick_hz();
            unsigned us = (hz > 0u && d.aus_fed > 0)
                ? (unsigned)((d.decode_ticks * 1000000u) / hz / (unsigned)d.aus_fed) : 0u;

            /* Submission only - the decode itself runs on the SPEs and finishes on a callback, so this
             * is NOT comparable to openh264's per-call number and must not be read as one. */
            ps3_log("       %u us per vdecDecodeAu call - SUBMISSION, not decode: the work happens\n"
                    "       on the SPEs and lands on a callback, so this is not openh264's number\n", us);
        }
        {
            int i;

            for (i = 0; i < d.hashes; i++)
                ps3_log("       frame %2d  0x%016llx\n", i, (unsigned long long)d.hash[i]);
            ps3_log("       COMPARE THESE with the dec: hashes below. Equal means the two decoders\n"
                    "       agree on this capture, which is the evidence needed before the live path\n"
                    "       moves onto one nobody here has run.\n");
        }
        {
            /* b151 showed the two disagree while both report 640x360, so the first picture is pulled
             * apart here - see rc_vdec_probe.h. The chroma is hashed at both candidate offsets; the one
             * that matches openh264's U says where this decoder puts its planes. */
            ps3_log("       first picture, by plane (coded height would be %d):\n", d.padded_height);
            ps3_log("         Y              0x%016llx\n", (unsigned long long)d.hash_y);
            ps3_log("         U after %3d rows 0x%016llx\n", d.height,
                    (unsigned long long)d.hash_u_at_visible);
            ps3_log("         U after %3d rows 0x%016llx\n", d.padded_height,
                    (unsigned long long)d.hash_u_at_padded);
            ps3_log("         V after %3d rows 0x%016llx\n", d.height,
                    (unsigned long long)d.hash_v_at_visible);
            ps3_log("         V after %3d rows 0x%016llx\n", d.padded_height,
                    (unsigned long long)d.hash_v_at_padded);
            log_bytes("row 0", d.first_luma, 16);
            log_bytes("row 1", d.second_row_luma, 16);
            if (!d.diff_valid) {
                ps3_log("       no reference luma to diff against (openh264 gave %dx%d)\n",
                        rc_decode_reference_width, rc_decode_reference_height);
            } else if (d.diff_first_offset < 0) {
                ps3_log("       LUMA IDENTICAL to openh264 over all %ld bytes\n", d.diff_total);
            } else {
                ps3_log("       luma differs in %ld of %ld bytes (%ld%%)\n",
                        d.diff_bytes, d.diff_total,
                        (d.diff_total > 0) ? (d.diff_bytes * 100 / d.diff_total) : 0);
                ps3_log("       first difference at row %d col %d (offset %ld)\n",
                        d.diff_first_row, d.diff_first_col, d.diff_first_offset);
                log_bytes("openh264", d.diff_reference, 8);
                log_bytes("vdec    ", d.diff_actual, 8);
                ps3_log("       rows affected %d of %d (rows %d..%d), columns %d..%d,"
                        " %ld of them in the last 16 columns\n",
                        d.diff_rows_affected, d.height, d.diff_min_row, d.diff_max_row,
                        d.diff_min_col, d.diff_max_col, d.diff_in_last_16_cols);
                ps3_log("       largest difference %d, mean %ld/100, and %ld of them exceed 4\n",
                        d.diff_max_delta, d.diff_delta_sum * 100 / (d.diff_bytes > 0 ? d.diff_bytes : 1),
                        d.diff_over_4);
                if (d.diff_max_delta <= 4 && d.diff_min_col >= d.width - 16)
                    ps3_log("       VERDICT: the decoders agree. What differs is the last few columns,\n"
                            "       by amounts no viewer can see. That is a usable decoder.\n");
                {
                    int k;

                    ps3_log("       the last 16 columns, where the first 8 agree and the last 8 do not:\n");
                    for (k = 0; k < d.edge_rows; k++) {
                        ps3_log("       row %d:\n", d.edge_row[k]);
                        log_bytes("openh264", d.edge_ref[k], 16);
                        log_bytes("vdec    ", d.edge_act[k], 16);
                    }
                    if (d.edge_found_at >= 0)
                        ps3_log("       vdec's last 8 also occur at column %d of openh264's row -"
                                " it is a copy of something, not new pixels\n", d.edge_found_at);
                    else
                        ps3_log("       vdec's last 8 occur nowhere else in openh264's row, so they are\n"
                                "       their own pixels rather than a repeated block\n");
                }
                if (d.found_row_stride > 0)
                    ps3_log("       the reference's row 1 sits at offset %d, so the stride is %d"
                            " (the picture is %d wide)\n",
                            d.found_row_stride, d.found_row_stride, d.width);
                else
                    ps3_log("       the reference's row 1 does not occur anywhere in the first 2048\n"
                            "       bytes, so the planes are not merely offset from each other.\n");
            }
            ps3_log("       the output buffer is at 0x%08X (%s128-byte aligned)\n",
                    d.buffer_addr, (d.buffer_addr & 127u) == 0u ? "" : "NOT ");
            ps3_log("       the decoder says the picture occupies %u bytes"
                    " (status %u, attr %u)\n",
                    d.picture_size, d.picture_status, d.picture_attr);
            if (d.matched_stride > 0)
                ps3_log("       STRIDE FOUND: %d bytes per luma row reproduces openh264's luma exactly\n",
                        d.matched_stride);
            else
                ps3_log("       NO STRIDE from %d to 2048 reproduces openh264's luma. The difference is\n"
                        "       then in the pixels rather than their arrangement - a colour matrix\n"
                        "       applied to YUV output, or a different chroma siting.\n", d.width);
            if (d.matched_luma_rows > 0)
                ps3_log("       CHROMA FOUND: it begins after %d luma rows (visible height is %d)\n",
                        d.matched_luma_rows, d.height);
            else if (d.matched_stride > 0)
                ps3_log("       chroma not located at any row count up to 2048 with that stride\n");
        }
    }
    return 0;
}

static int check_crypto_speed(void)
{
    /* rc_gmac_key carries ~5 KB of tables - far too much for a stack frame on this port. */
    static rc_gmac_key gk;
    static uint8_t buffer[RC_CRYPTO_BENCH_PACKET];

    /* FIPS-197 C.1: the one published AES-128 vector, checked here on the console's own toolchain. */
    static const uint8_t kFipsKey[16] = {
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f
    };
    static const uint8_t kFipsPlain[16] = {
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
        0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff
    };
    static const uint8_t kFipsCipher[16] = {
        0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30,
        0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a
    };

    rc_aes128 aes;
    uint8_t block[16];
    uint8_t nonce[16];
    uint8_t tag[16];
    uint64_t hz = rc_tick_hz();
    uint64_t t0;
    uint64_t block_ticks, ctr_ticks, gmac_ticks, init_ticks;
    unsigned aes_ns, gmac_ns, ctr_us, gmac_us, init_us, packet_us;
    int i;

    rc_aes128_init(&aes, kFipsKey);
    rc_aes128_encrypt_block(&aes, kFipsPlain, block);
    if (memcmp(block, kFipsCipher, sizeof(block)) != 0) {
        ps3_log("FAIL  AES-128 does not match FIPS-197 C.1 on this target\n");
        ps3_log("      the word-at-a-time rewrite is wrong here even though the host suite passes -\n");
        ps3_log("      suspect the big-endian load/store helpers in rc_aes.c.\n");
        return 1;
    }

    for (i = 0; i < RC_CRYPTO_BENCH_PACKET; i++)
        buffer[i] = (uint8_t)i;
    memset(nonce, 0x5a, sizeof(nonce));

    /* One block of the forward permutation, with the schedule already expanded. */
    t0 = rc_tick();
    for (i = 0; i < RC_CRYPTO_BENCH_BLOCKS; i++)
        rc_aes128_encrypt_block(&aes, block, block);
    block_ticks = rc_tick() - t0;

    /* A full-MTU CTR pass - the payload half of what the demuxer does per packet. */
    t0 = rc_tick();
    for (i = 0; i < RC_CRYPTO_BENCH_PASSES; i++)
        rc_aes128_ctr(kFipsKey, nonce, buffer, buffer, sizeof(buffer), 1);
    ctr_ticks = rc_tick() - t0;

    /* Building the GHASH tables: once per key rotation, so this is amortised over ~650 packets. */
    t0 = rc_tick();
    for (i = 0; i < RC_CRYPTO_BENCH_PASSES; i++)
        rc_gmac_key_init(&gk, kFipsKey);
    init_ticks = rc_tick() - t0;

    /* A full-MTU GMAC under a prepared key - the tag half. */
    t0 = rc_tick();
    for (i = 0; i < RC_CRYPTO_BENCH_PASSES; i++)
        rc_gmac_with_key(&gk, nonce, sizeof(nonce), buffer, sizeof(buffer), tag);
    gmac_ticks = rc_tick() - t0;

    aes_ns = bench_ns(block_ticks, hz, RC_CRYPTO_BENCH_BLOCKS);
    ctr_us = bench_us(ctr_ticks, hz, RC_CRYPTO_BENCH_PASSES);
    gmac_us = bench_us(gmac_ticks, hz, RC_CRYPTO_BENCH_PASSES);
    init_us = bench_us(init_ticks, hz, RC_CRYPTO_BENCH_PASSES);
    /* GHASH processes one 16-byte block per multiply; %d bytes is that many blocks plus the length block. */
    gmac_ns = bench_ns(gmac_ticks, hz, RC_CRYPTO_BENCH_PASSES * (RC_CRYPTO_BENCH_PACKET / 16));
    packet_us = ctr_us + gmac_us;

    ps3_log("cryp:  AES-128 matches FIPS-197 C.1\n");
    ps3_log("cryp:  one AES block          %u ns\n", aes_ns);
    ps3_log("cryp:  one GHASH block        %u ns\n", gmac_ns);
    ps3_log("cryp:  CTR over %d bytes    %u us\n", RC_CRYPTO_BENCH_PACKET, ctr_us);
    ps3_log("cryp:  GMAC over %d bytes   %u us\n", RC_CRYPTO_BENCH_PACKET, gmac_us);
    ps3_log("cryp:  GHASH table build      %u us (once per ~650 packets, not per packet)\n", init_us);
    ps3_log("cryp:  => one A/V packet      %u us of crypto\n", packet_us);
    ps3_log("cryp:  b140 measured 837 us per packet through the demuxer's crypto seam\n");
    return 0;
}

static int check_decode(void)
{
    rc_decode_probe_result r;
    uint64_t hz = rc_tick_hz();
    int i;

    if (!rc_decode_probe(RC_DECODE_STREAM_PATH, RC_DECODE_FRAMES, &r)) {
        if (!r.opened) {
            /* Not a failure - see above. */
            ps3_log("dec:   no stream at %s - skipping (copy the capture there to run it)\n",
                    RC_DECODE_STREAM_PATH);
            return 0;
        }
        ps3_log("FAIL  openh264 read %u bytes and produced no frame\n", (unsigned)r.bytes);
        ps3_log("      initialised=%d nals=%d frames=%d last_error=%ld\n",
                r.initialised, r.nals_fed, r.frames_out, (long)r.last_error);
        return 1;
    }

    ps3_log("dec:   %u bytes, %d NALs fed, %d frames out, %dx%d\n",
            (unsigned)r.bytes, r.nals_fed, r.frames_out, r.width, r.height);
    for (i = 0; i < r.hashes; i++)
        ps3_log("       frame %3d  0x%016llx\n", i, (unsigned long long)r.hash[i]);

    if (r.frames_out > 0 && r.decode_ticks > 0u) {
        uint64_t us = r.decode_ticks * 1000000ULL / hz;
        uint64_t per_frame_us = us / (uint64_t)r.frames_out;
        /* Tenths, because integer fps loses the difference between 4 and 4.9 and this number is about
         * to be multiplied by four to guess at 720p. */
        uint64_t fps_tenths = (per_frame_us > 0u) ? (10000000ULL / per_frame_us) : 0u;

        ps3_log("       PPE alone: %llu frames in %llu ms, %llu us/frame, %llu.%llu fps\n",
                (unsigned long long)r.frames_out,
                (unsigned long long)(us / 1000ULL),
                (unsigned long long)per_frame_us,
                (unsigned long long)(fps_tenths / 10ULL),
                (unsigned long long)(fps_tenths % 10ULL));
        ps3_log("       (hashing %d frames cost %llu ms and is NOT in the above)\n",
                r.hashes, (unsigned long long)(r.hash_ticks * 1000000ULL / hz / 1000ULL));
        ps3_log("       (this is %dx%d - 720p is ~4x the pixels)\n", r.width, r.height);
    }

    s_reference_hash_y = r.hash_y;
    s_reference_hash_u = r.hash_u;
    ps3_log("       first picture, by plane (strides: Y %d, UV %d):\n", r.stride_y, r.stride_uv);
    ps3_log("         Y  0x%016llx\n", (unsigned long long)r.hash_y);
    ps3_log("         U  0x%016llx\n", (unsigned long long)r.hash_u);
    ps3_log("         V  0x%016llx\n", (unsigned long long)r.hash_v);
    log_bytes("row 0", r.first_luma, 16);
    log_bytes("row 1", r.second_row_luma, 16);
    ps3_log("ok    openh264 decoded on the PPE - compare the hashes with the reference decode\n");
    return 0;
}

/*
 * THE TEST PATTERN, and it is designed to be read rather than merely seen.
 *
 * "Something appeared" is a weak result. Each element here answers a different question, so a partial
 * failure still says which part is wrong:
 *
 *   - the WHITE BORDER, one pixel inside every edge, shows the buffer's real extent. If it is clipped
 *     or doubled, width/height/pitch disagree with what the display expects - the classic symptom of
 *     assuming pitch == width * 4.
 *   - the COLOUR BARS are pure red, green and blue in that order from the left. Wrong order means the
 *     byte order is BGR rather than RGB; missing channels mean the format is not XRGB8888.
 *   - the DIAGONAL runs corner to corner. A stair-stepped or doubled diagonal means the pitch is being
 *     applied wrongly per line, which a flat colour would hide completely.
 *   - the GREY WEDGE across the bottom shows whether the full range survives, not just saturated values.
 *
 * Written with the CPU, one pixel at a time. At this size that is not fast, and it does not need to be:
 * nothing is being timed here, and a slow correct picture is the point.
 */
static void draw_test_pattern(uint32_t *buffer, int width, int height, int pitch, int frame)
{
    const int stride = pitch / 4;   /* pixels per line, which is what the pointer arithmetic wants */
    int x, y;

    for (y = 0; y < height; y++) {
        uint32_t *line = buffer + (size_t)y * (size_t)stride;

        for (x = 0; x < width; x++) {
            uint32_t colour;

            if (x == 1 || y == 1 || x == width - 2 || y == height - 2) {
                colour = 0x00ffffffu;                       /* the extent marker */
            } else if (y > height - height / 8) {
                unsigned g = (unsigned)((x * 255) / (width > 1 ? width - 1 : 1));
                colour = (g << 16) | (g << 8) | g;          /* the grey wedge */
            } else if (x * 3 / width == 0) {
                colour = 0x00ff0000u;                       /* red   */
            } else if (x * 3 / width == 1) {
                colour = 0x0000ff00u;                       /* green */
            } else {
                colour = 0x000000ffu;                       /* blue  */
            }

            /* The diagonal last, so it draws over the bars rather than being hidden by them. */
            if (height > 1 && x == (y * width) / height)
                colour = 0x00ffff00u;

            line[x] = colour;
        }
    }

    /*
     * A MOVING BLOCK, because a static image cannot distinguish "flipping correctly" from "one frame
     * was drawn and nothing has happened since". If it does not move, the flip is not working even
     * though the picture is.
     */
    {
        int bw = width / 16;
        int bh = height / 16;
        int bx = (frame * 8) % (width - bw > 0 ? width - bw : 1);
        int by = height / 3;

        for (y = by; y < by + bh && y < height; y++) {
            uint32_t *line = buffer + (size_t)y * (size_t)stride;
            for (x = bx; x < bx + bw && x < width; x++)
                line[x] = 0x00ffffffu;
        }
    }
}

static int check_display(void)
{
    rc_video_info info;
    int frame;

    ps3_log("\nvid:   bringing up the display\n");

    if (!rc_video_open(&info)) {
        /* In hex as well as signed. lv2 error codes are documented as 0x8-prefixed words and are
         * unrecognisable as negative decimals - b80's -2145320705 is 0x802100FF, and looking that up
         * cost a step that printing it would not have. */
        ps3_log("FAIL  display did not come up: %s (code %d = 0x%08X)\n",
                info.failed_at != NULL ? info.failed_at : "unknown step",
                info.last_error, (unsigned)info.last_error);
        ps3_log("      the step is named because \"no picture\" says nothing on its own\n");
        ps3_log("      %d size combination(s) tried, all refused\n", info.rsx_attempts);
        ps3_log("      sysModuleLoad: GCM_SYS 0x%08X, SYSUTIL 0x%08X (non-zero may just mean\n"
                "      already loaded - these are PRXes and nothing in them exists unloaded)\n",
                (unsigned)info.gcm_module, (unsigned)info.sysutil_module);
        return 1;
    }

    ps3_log("       rsxInit took %d attempt(s): command buffer %d bytes in a %d byte IO region\n",
            info.rsx_attempts, info.cmd_size, info.io_size);
    ps3_log("       modules: GCM_SYS 0x%08X, SYSUTIL 0x%08X\n",
            (unsigned)info.gcm_module, (unsigned)info.sysutil_module);
    ps3_log("       %dx%d, pitch %d bytes (%d bytes/pixel), %d buffers, videoGetState reported %d\n",
            info.width, info.height, info.pitch,
            info.width > 0 ? info.pitch / info.width : 0, info.buffers, info.video_state);

    /*
     * Held for a few seconds rather than flashed. The point is a human looking at a television, and
     * the elements are meant to be read off it - see draw_test_pattern.
     */
    /* One second, not three. The pattern only has to be seen to be checked, and everything after it
     * is more interesting. */
    for (frame = 0; frame < 60; frame++) {
        uint32_t *back = rc_video_back_buffer();

        if (back == NULL) {
            ps3_log("FAIL  no back buffer after the display opened\n");
            rc_video_close();
            return 1;
        }
        draw_test_pattern(back, info.width, info.height, info.pitch, frame);
        rc_video_flip();
    }

    ps3_log("ok    %d frames drawn and flipped. WHAT TO LOOK FOR:\n", frame);
    ps3_log("      a white border one pixel inside every edge  - the buffer's true extent\n");
    ps3_log("      red, green, blue bars left to right         - byte order and pixel format\n");
    ps3_log("      a clean yellow diagonal, corner to corner   - the pitch applied per line\n");
    ps3_log("      a grey wedge along the bottom               - the full range, not just saturation\n");
    ps3_log("      a white block sliding left to right         - flipping, not one stuck frame\n");
    ps3_log("      (the border and the diagonal are ONE PIXEL wide - at 1080p on a television\n");
    ps3_log("       overscan eats the first and the second is near-invisible over the bars. The\n");
    ps3_log("       bars landing in the right thirds already proves the pitch: a wrong one skews\n");
    ps3_log("       every line progressively and could not look tidy.)\n");
    /*
     * LEFT OPEN on purpose. The connect stage puts live frames on this screen, and closing the display
     * here would mean bringing it up twice - the one call in this port with a history of refusing.
     * main() closes it at the end.
     */
    return 0;
}

int main(void)
{
    int failures = 0;
    int chosen;
    int lv2_dir;
    int i;

    /*
     * Pick a log directory by trying them, not by believing one. See RC_PS3_LOG_DIRS above for why.
     *
     * rc_log_open takes a path and uses its directory part, so a string that already ends in '/' names
     * itself - that is rc_program_dir's documented behaviour, not a trick. Passing NULL would take the
     * Makefile's compile-time fallback instead, which is exactly the assumption that produced a silent
     * first run.
     */
    /*
     * THE BEACON. Literally the first thing, and deliberately the stupidest thing in this file.
     *
     * Two runs have now produced no output whatsoever, and each time the question was the same: did the
     * program not start, or did it start and fail to tell us? Every answer this file gives costs stack -
     * a path buffer, a snprintf, a call into rc_log - and if the stack is what is wrong then every one
     * of them is unavailable precisely when it is needed.
     *
     * So this uses a string literal, one s32, and one syscall. No buffer, no formatting, no helper. If
     * ripcord-alive.txt exists after a run, main() was entered and lv2 accepted a write, and everything
     * after this point is an ordinary bug. If it does not, the program is dying before or at its first
     * instruction and no amount of logging machinery downstream would ever have shown it.
     *
     * It is not diagnostic scaffolding to be removed once this is solved. It costs one syscall at
     * startup and it is the only thing in the program that can distinguish "did not run" from "ran
     * badly", which is the distinction that cost the most time here.
     */
    {
        s32 beacon_fd = -1;
        if (sysLv2FsOpen("/dev_hdd0/ripcord-alive.txt",
                         SYS_O_WRONLY | SYS_O_CREAT | SYS_O_TRUNC,
                         &beacon_fd, 0666u, NULL, 0u) == 0) {
            u64 wrote = 0u;
            /* The build id goes in the beacon too. It is the one artifact that survives every failure
             * mode below, so it is the one that most needs to say which binary produced it. */
            (void)sysLv2FsWrite(beacon_fd, RC_PS3_BUILD_ID " main() entered\n",
                                (u64)(sizeof(RC_PS3_BUILD_ID " main() entered\n") - 1u), &wrote);
            (void)sysLv2FsClose(beacon_fd);
        }
    }

    /* Record the stack base while main's frame is still the only one - see rc_stack_ps3.h. */
    rc_stack_probe_init();

    /*
     * THE NETWORK CHANNEL FIRST OF ALL, because it is the only one that needs no write permission
     * anywhere. A program launched by ps3load transfers, spawns, blacks the screen and writes nothing to
     * disk; if its sandbox is what denies the file channels, this is the only voice it has.
     *
     * RC_NETLOG_HOST and RC_NETLOG_PORT come from the Makefile. Failure is ignored: a console with no
     * network is still a console worth running the rest of these checks on.
     */
    (void)rc_netlog_open(RC_NETLOG_HOST, RC_NETLOG_PORT);

    /* THE LV2 CHANNEL FIRST of the file channels, because it is the one that has to work. Opened before anything else in
     * the program so that a crash after this point still leaves a file behind - an empty
     * ps3-bringup-lv2.log is itself the finding that main() was entered. */
    for (lv2_dir = 0; lv2_dir < LOG_DIR_COUNT; lv2_dir++) {
        if (lv2_log_open(g_log_dirs[lv2_dir], "ps3-bringup-lv2.log"))
            break;
    }

    for (chosen = 0; chosen < LOG_DIR_COUNT; chosen++) {
        if (dir_accepts_a_file(g_log_dirs[chosen], "ps3-bringup.log"))
            break;
    }

    if (chosen < LOG_DIR_COUNT) {
        rc_log_open(g_log_dirs[chosen], "ps3-bringup.log");
    } else {
        /* Nothing took a file through newlib. That is a finding, not a fallback - it is reported in the
         * table below, and the lv2 channel above is what carries this run's output. */
        rc_log_open(NULL, "ps3-bringup.log");
    }

    ps3_log("ripcord-ps3 platform bring-up, build %s\n", RC_PS3_BUILD_ID);
    ps3_log("=========================================\n");
    ps3_log("If that build id is not the one `make` just printed, the console is running a stale\n");
    ps3_log("install and nothing below this line means anything.\n\n");

    /* The table, logged rather than merely acted on. This is the first thing a PS3 has ever been asked
     * about this port, and "which directories may a packaged homebrew write to" is worth answering once
     * and keeping. */
    ps3_log("log:   channels carrying this run\n");
    ps3_log("       [%c] udp to %s:%u  (first sendto returned %ld)\n",
            rc_netlog_is_open() ? 'x' : ' ', RC_NETLOG_HOST, (unsigned)RC_NETLOG_PORT,
            rc_netlog_first_send_result());
    ps3_log("       [%c] lv2 syscalls (sysLv2FsOpen)   %s\n",
            (g_lv2_fd >= 0) ? 'x' : ' ',
            (g_lv2_dir != NULL) ? g_lv2_dir : "- nowhere accepted a file");
    ps3_log("       [%c] newlib stdio (fopen)          %s\n",
            (chosen < LOG_DIR_COUNT) ? 'x' : ' ',
            (chosen < LOG_DIR_COUNT) ? g_log_dirs[chosen] : "- ENOSYS everywhere, see main.c");
    ps3_log("\n");

    ps3_log("log:   writable-directory probe, in preference order\n");
    for (i = 0; i < LOG_DIR_COUNT; i++) {
        int fop = dir_accepts_a_file(g_log_dirs[i], "ps3-bringup.log");
        /* Both channels asked about the same directory. Where they disagree, the layer is the problem
         * rather than the path - which is the single most useful thing this run can establish. */
        ps3_log("       fopen[%c] lv2[%c] %s%s\n",
               fop ? 'x' : ' ',
               (i == lv2_dir) ? 'x' : '?',
               g_log_dirs[i],
               (i == chosen) ? "   <- newlib log" : "");
    }
    ps3_log("\n");

    /* The timestamp step 4 promised. It is also the first thing that proves the seam linked at all. */
    ps3_log("boot:  rc_time_ms() = %llu ms since power-on\n", (unsigned long long)rc_time_ms());
    ps3_log("       rc_tick()    = %llu\n\n", (unsigned long long)rc_tick());

    failures += measure_timebase();
    /*
     * THE DISPLAY GOES FIRST, and the order is the experiment.
     *
     * rsxInit has refused with 0x802100FF across three builds - a 512 KB IO region (a real bug, fixed),
     * a 1 MB one, and one with GCM_SYS and SYSUTIL both loading successfully. Three hypotheses about the
     * call itself, all wrong, which is a sign the question is not about the call.
     *
     * What the call has always had in common is WHEN it happens: dead last, after netInitialize, after
     * a raw SPU has been created and torn down, after openh264 and mbedtls have taken whatever they
     * take, and after the decoder has run. Any of those could hold a resource the RSX needs, and none of
     * them can be ruled out by reading rsx.h.
     *
     * So the display is attempted before any of it. If it comes up here, the subject is something this
     * program does earlier and the bisection continues downward. If it refuses here too, on a freshly
     * started process that has done nothing but open its log files, then it is about how this program is
     * built or launched and not about anything it runs.
     *
     * The order goes back once that is answered. It is a diagnostic arrangement, not a design.
     */
    failures += check_display();

    failures += check_monotonic();
    failures += check_csprng();
    failures += check_spu();
    failures += check_core();

    /*
     * THE COLOUR-CONVERSION SPEs, BEFORE THE STAGE THAT USES THEM.
     *
     * b99 brought these up after check_decode, which reads sensibly and runs far too late: the
     * conversion happens inside check_connect, which is two lines above it. Five SPEs came up, converted
     * nothing, and the blit stayed at the PPE's 11869 us - a change that did exactly nothing and looked
     * like a change that did not work.
     *
     * After check_spu, because that is what initialises the SPU subsystem for this process. Before
     * check_connect, because that is what needs them. Both constraints are on the ORDER, which is why
     * this sits between them rather than wherever it read best.
     *
     * Not a check in its own right: a console that gives this program no SPEs still streams, on the PPE,
     * at the speed the last several runs measured.
     */
    {
        int spes = rc_spu_yuv_init();
        rc_spu_yuv_stats stats;

        rc_spu_yuv_stats_get(&stats);
        if (spes > 0) {
            int checked = 0, match = 0;
            uint64_t spu_hash = 0, ppe_hash = 0;

            ps3_log("\nspu:   %d SPE(s) up for colour conversion\n", spes);

            /*
             * The agreement check, HERE and not on the first streamed frame. It used to run there, and
             * at 1080p the stall cost the Takion channel - b112 received 58 packets where the run before
             * received 6287. A synthetic picture tests the same thing better and costs the stream
             * nothing.
             */
            (void)rc_video_self_test();
            rc_video_verify_get(&checked, &match, &spu_hash, &ppe_hash);
            if (!checked)
                ps3_log("spu:   the conversions were not compared - the SPEs refused the test picture\n");
            else if (match)
                ps3_log("ok    SPE and PPE agree at 2x, 1.5x, 1:1 and 0.75x, over the full value range"
                        " (0x%016llx)\n", (unsigned long long)spu_hash);
            else
                ps3_log("FAIL  the conversions disagree at %s: SPE 0x%016llx != PPE 0x%016llx\n",
                        rc_video_self_test_failure() != NULL ? rc_video_self_test_failure() : "?",
                        (unsigned long long)spu_hash, (unsigned long long)ppe_hash);
        } else {
            ps3_log("\nspu:   no SPEs for colour conversion (step %d, 0x%08X) - the PPE path stands\n",
                    stats.init_failed_at, (unsigned)stats.last_error);
        }
    }

    failures += check_discovery();
    failures += check_connect();
    failures += check_crypto_speed();
    failures += check_decode();
    /*
     * LAST, because it is the stage that can hang. b146 stopped inside it and took the crypto and decode
     * results with it - those had already run, but the console froze before anything after this point
     * could be written. A stage that might not return belongs after every stage that must.
     */
    failures += check_vdec();

    ps3_log("\nnot covered here: the rest of the decoder. See README.md.\n");
    ps3_log("%s\n", failures == 0 ? "all checks passed" : "CHECKS FAILED");
    /* The generator was opened by the CSPRNG check and used by everything after it - see the note
     * there. It is closed here, with the other process-wide resources, rather than by any one check. */
    {
        rc_spu_yuv_stats stats;

        rc_spu_yuv_stats_get(&stats);
        if (stats.frames > 0u || stats.fallbacks > 0u) {
            ps3_log("spu:   %u frame(s) converted on %d SPE(s), %u us average, %u us worst;"
                    " %u fell back to the PPE\n",
                    stats.frames, stats.spes, stats.avg_us, stats.worst_us, stats.fallbacks);

            if (stats.disabled)
                ps3_log("spu:   the SPE path was ABANDONED after repeated misses - the PPE carried the\n"
                        "       rest of the run, which is the outcome this is designed to produce\n");

            {
                unsigned calls = 0, busy = 0, last = 0;

                rc_video_flip_stats(&calls, &busy, &last);
                ps3_log("vid:   flip-ready asked %u time(s), %u said busy, last raw status %u\n",
                        calls, busy, last);
            }

        }
    }
    /*
     * THE LOGS CLOSE FIRST, and the order is not tidiness.
     *
     * b107 ran the whole stream successfully and then froze in the teardown below, which meant the last
     * thing written was whatever happened to be flushed - and the teardown is precisely where this port
     * has now hung twice. Anything that can hang belongs AFTER the evidence is on disk, so that a frozen
     * console costs a reboot rather than the run that explains it.
     */
    lv2_log_close();
    rc_log_close();
    rc_netlog_close();

    rc_spu_yuv_exit();
    rc_video_close();
    rc_random_exit();

    return failures == 0 ? 0 : 1;
}
