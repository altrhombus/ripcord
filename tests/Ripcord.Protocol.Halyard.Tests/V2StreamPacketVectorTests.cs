using System.Text.Json;
using Ripcord.Protocol.Halyard.Common.Crypto;
using Ripcord.Protocol.Halyard.Common.Crypto.V1;
using Ripcord.Protocol.Halyard.Common.Crypto.V2;
using Xunit;

namespace Ripcord.Protocol.Halyard.Tests;

/// <summary>
/// Byte-exact checks of the v2 (PS5) stream plane against the console's own outputs (sessions 003/004):
/// the per-direction key schedule (<c>HMAC(Z_stream, 01|dir|00|X|0100)</c>, dir 2 c2s / 3 s2c), the
/// <c>ecdhSignature = HMAC(X, pubkey)</c>, and the s2c A/V per-packet GMAC + AES-CTR with the v2 header layout
/// (tag@18, key_pos@22, payload@26) and the v2 GMAC window rule <c>(key_pos-1)/45000</c>.
///
/// <para>These exercise exactly what <see cref="HalyardV2SessionCrypto"/> uses internally
/// (<see cref="HalyardStreamKeySchedule"/> + <see cref="HalyardPacketCrypto"/> with
/// <see cref="HalyardGmacWindowRule.FromKeyPosMinusOne"/>). The secret <c>X</c> comes from the fixture (a
/// captured value); the client cannot yet derive X live (its origin is an unresolved <c>[X]</c>,
/// <c>X-ORIGIN-CORRECTION-2026-10-20.md</c>), so the stream plane is proven here, not on hardware.</para>
///
/// <para>Fixture <c>docs/protocol/captures/v2_control_key_vectors.json</c> is gitignored (live stream material);
/// generated by <c>v2-validation/extract_v2_key_vectors.py</c>. Skips when absent so CI stays green.</para>
/// </summary>
public class V2StreamPacketVectorTests
{
    private const int AvTagOffset = 18;
    private const int AvKeyPosOffset = 22;
    private const int AvPayloadOffset = 26;

    /// <summary>The stream key schedule reproduces the console's per-direction keys (dir 2 c2s / 3 s2c).</summary>
    [SkippableFact]
    public void StreamKeySchedule_ReproducesCapturedPerDirectionKeys()
    {
        var fx = LoadOrSkip();
        Skip.If(fx.Stream is not { Count: > 0 }, "Fixture has no stream vectors.");

        foreach (var v in fx.Stream!)
        {
            byte[] z = Hex.Bytes(v.Z!);
            byte[] x = Hex.Bytes(v.X!);
            AssertDirection(z, x, HalyardStreamKeySchedule.DirectionClientToServer, v.SkClientToConsole!);
            AssertDirection(z, x, HalyardStreamKeySchedule.DirectionServerToClient, v.SkConsoleToClient!);
        }
    }

    private static void AssertDirection(byte[] z, byte[] x, byte dir, string expectedHex)
    {
        var keys = HalyardStreamKeySchedule.DeriveDirection(z, x, dir);
        byte[] sk = [.. keys.AesKey, .. keys.BaseIv];
        Assert.Equal(expectedHex.ToLowerInvariant(), Hex.String(sk));
    }

    /// <summary><c>ecdhSignature = HMAC-SHA256(X, publicKey)</c> reproduces the on-wire SESSION_REQUEST field.</summary>
    [SkippableFact]
    public void EcdhSignature_ReproducesCapturedValue()
    {
        var fx = LoadOrSkip();
        Skip.If(fx.EcdhSignatures is not { Count: > 0 }, "Fixture has no ecdhSignature vectors.");

        foreach (var v in fx.EcdhSignatures!)
        {
            byte[] sig = HalyardStreamKeySchedule.ComputeEcdhSignature(Hex.Bytes(v.X!), Hex.Bytes(v.PublicKey!));
            Assert.Equal(v.Signature!.ToLowerInvariant(), Hex.String(sig));
            Assert.True(HalyardStreamKeySchedule.VerifyEcdhSignature(
                Hex.Bytes(v.X!), Hex.Bytes(v.PublicKey!), Hex.Bytes(v.Signature!)));
        }
    }

    /// <summary>
    /// Every captured s2c A/V packet's 4-byte GMAC reproduces under the v2 rule (tag@18, window=(key_pos-1)/45000),
    /// and AES-CTR decrypts the payload to the captured plaintext head. Packets span several rotation windows, so
    /// this exercises the v2 window rotation, not just window 0.
    /// </summary>
    [SkippableFact]
    public void AvPacket_GmacAndCtr_ReproduceAcrossWindows()
    {
        var fx = LoadOrSkip();
        Skip.If(fx.StreamPackets is not { Count: > 0 }, "Fixture has no stream-packet vectors.");

        int checkedAboveWindow0 = 0;
        foreach (var v in fx.StreamPackets!)
        {
            using var crypto = new HalyardPacketCrypto(
                Hex.Bytes(v.AesKey!), Hex.Bytes(v.BaseIv!), HalyardGmacWindowRule.FromKeyPosMinusOne);

            byte[] packet = Hex.Bytes(v.Packet!);
            Assert.Equal(v.Tag, Hex.String(crypto.ComputeTag(v.KeyPos, packet, AvTagOffset)));
            Assert.True(crypto.VerifyPacket(v.KeyPos, packet, AvTagOffset));

            byte[] head = crypto.CryptPayload(v.KeyPos, packet.AsSpan(AvPayloadOffset))[..16];
            Assert.Equal(v.PlaintextHead, Hex.String(head));

            if (v.Window > 0) checkedAboveWindow0++;
        }

        Assert.True(checkedAboveWindow0 > 0,
            "Fixture exercised only window 0 — the v2 (key_pos-1)/45000 rotation was not tested.");
    }

    /// <summary>
    /// The two GMAC window rules (v1 <c>keyPos/45000</c>, v2 <c>(keyPos-1)/45000</c>) diverge <b>exactly</b> at
    /// multiples of 45000 and agree everywhere else — so the v2 <c>-1</c> is not discriminable from wire tags on
    /// non-boundary packets (it was pinned from the client's own per-window GMAC-key ground truth,
    /// <c>validate_v2_av_packets.py</c>). This pins the divergence the code must implement.
    /// </summary>
    [Fact]
    public void WindowRules_DivergeExactlyAtMultiplesOf45000()
    {
        byte[] key = Convert.FromHexString("000102030405060708090a0b0c0d0e0f");
        byte[] iv = Convert.FromHexString("0f0e0d0c0b0a09080706050403020100");
        using var v1 = new HalyardPacketCrypto(key, iv, HalyardGmacWindowRule.FromKeyPos);
        using var v2 = new HalyardPacketCrypto(key, iv, HalyardGmacWindowRule.FromKeyPosMinusOne);

        Span<byte> a = stackalloc byte[16];
        Span<byte> b = stackalloc byte[16];
        foreach (ulong keyPos in new ulong[] { 0, 1, 44999, 45000, 45001, 89999, 90000, 90001, 3240000 })
        {
            v1.GmacKey(keyPos, a);
            v2.GmacKey(keyPos, b);
            bool shouldDiffer = keyPos != 0 && keyPos % 45000 == 0; // v1 window = n, v2 window = n-1
            Assert.Equal(shouldDiffer, !a.SequenceEqual(b));
        }
    }

    /// <summary>
    /// The v2 per-packet path round-trips symmetrically at a window&gt;0 key position (so the v2 rotation runs):
    /// encrypt-then-MAC then verify-then-decrypt recovers the payload, and a tampered tag fails. Uses one
    /// per-direction key from a real ECDH so the keys are genuine; byte-exact agreement with the console is the
    /// wire-KAT tests above.
    /// </summary>
    [Fact]
    public void V2PacketPath_RoundTripsAcrossARotationWindow()
    {
        byte[] x = Convert.FromHexString("0102030405060708090a0b0c0d0e0f10"); // synthetic X (any 16 B; these tests do not KAT the console)
        var (aEcdh, aPub) = HalyardStreamKeySchedule.GenerateKeyPair(HalyardStreamCurve.NistP521);
        var (bEcdh, bPub) = HalyardStreamKeySchedule.GenerateKeyPair(HalyardStreamCurve.NistP521);
        using (aEcdh)
        using (bEcdh)
        {
            byte[] z = HalyardStreamKeySchedule.DeriveSharedSecret(aEcdh, bPub);
            var dir = HalyardStreamKeySchedule.DeriveDirection(z, x, HalyardStreamKeySchedule.DirectionClientToServer);
            using var pc = new HalyardPacketCrypto(dir, HalyardGmacWindowRule.FromKeyPosMinusOne);

            const ulong keyPos = 90000; // window 1 under (keyPos-1)/45000
            byte[] packet = new byte[AvPayloadOffset + 48];
            Random.Shared.NextBytes(packet.AsSpan(AvPayloadOffset));
            byte[] original = (byte[])packet.Clone();

            // encrypt-then-MAC
            pc.CryptPayloadInPlace(keyPos, packet.AsSpan(AvPayloadOffset));
            pc.SealPacket(keyPos, packet, AvTagOffset).CopyTo(packet, 0);
            Assert.False(packet.AsSpan(AvPayloadOffset).SequenceEqual(original.AsSpan(AvPayloadOffset)));

            // verify-then-decrypt
            Assert.True(pc.VerifyPacket(keyPos, packet, AvTagOffset));
            pc.CryptPayloadInPlace(keyPos, packet.AsSpan(AvPayloadOffset));
            Assert.True(packet.AsSpan(AvPayloadOffset).SequenceEqual(original.AsSpan(AvPayloadOffset)));

            packet[AvTagOffset] ^= 0xFF;
            Assert.False(pc.VerifyPacket(keyPos, packet, AvTagOffset));
        }
    }

    /// <summary>
    /// <see cref="HalyardV2SessionCrypto"/> wires the key agreement + packet crypto together: after a stream
    /// establish it reports established and <see cref="HalyardV2SessionCrypto.SealPacket"/> encrypts the payload
    /// and writes a non-zero tag through the class's own (v2-window) packet crypto.
    /// </summary>
    [Fact]
    public void SessionCrypto_EstablishesStreamAndSeals()
    {
        byte[] x = Convert.FromHexString("0102030405060708090a0b0c0d0e0f10"); // synthetic X (any 16 B; these tests do not KAT the console)
        using var client = new HalyardV2SessionCrypto(TestSecrets.SyntheticControlSecrets());
        using var peer = new HalyardV2SessionCrypto(TestSecrets.SyntheticControlSecrets());

        byte[] clientPub = client.GenerateEphemeralPublicKey(0x11); // P-521
        byte[] peerPub = peer.GenerateEphemeralPublicKey(0x11);
        Assert.False(client.IsStreamEstablished);
        Assert.True(client.TryEstablishStream(peerPub, x));
        Assert.True(client.IsStreamEstablished);

        byte[] packet = new byte[AvPayloadOffset + 32];
        Random.Shared.NextBytes(packet.AsSpan(AvPayloadOffset));
        byte[] original = (byte[])packet.Clone();
        client.SealPacket(packet, new HalyardPacketLayout(90000, AvTagOffset, AvPayloadOffset));

        Assert.False(packet.AsSpan(AvPayloadOffset).SequenceEqual(original.AsSpan(AvPayloadOffset))); // encrypted
        Assert.NotEqual("00000000", Hex.String(packet.AsSpan(AvTagOffset, 4)));                       // tag written
    }

    // ---- fixture schema ----
    private sealed class Fixture
    {
        public List<StreamVector>? Stream { get; set; }
        public List<StreamPacket>? StreamPackets { get; set; }
        public List<EcdhVector>? EcdhSignatures { get; set; }
    }

    private sealed class StreamVector
    {
        public string? Z { get; set; }
        public string? X { get; set; }
        public string? SkClientToConsole { get; set; }
        public string? SkConsoleToClient { get; set; }
    }

    private sealed class StreamPacket
    {
        public string? AesKey { get; set; }
        public string? BaseIv { get; set; }
        public ulong KeyPos { get; set; }
        public int Window { get; set; }
        public string? Packet { get; set; }
        public string? Tag { get; set; }
        public string? PlaintextHead { get; set; }
    }

    private sealed class EcdhVector
    {
        public string? X { get; set; }
        public string? PublicKey { get; set; }
        public string? Signature { get; set; }
    }

    private static Fixture LoadOrSkip()
    {
        string path = LocateFixture();
        Skip.IfNot(File.Exists(path),
            $"Captures-folder fixture not present ({path}). Generate it with v2-validation/extract_v2_key_vectors.py.");
        return JsonSerializer.Deserialize<Fixture>(File.ReadAllText(path),
                   new JsonSerializerOptions { PropertyNameCaseInsensitive = true })
               ?? throw new InvalidOperationException("Fixture failed to deserialize.");
    }

    private static string LocateFixture()
    {
        string? env = Environment.GetEnvironmentVariable("RIPCORD_V2_KEY_FIXTURE");
        if (!string.IsNullOrEmpty(env) && File.Exists(env))
            return env;

        string? dir = AppContext.BaseDirectory;
        for (int i = 0; i < 8 && dir is not null; i++)
        {
            string candidate = Path.Combine(dir, "docs", "protocol", "captures", "v2_control_key_vectors.json");
            if (File.Exists(candidate))
                return candidate;
            dir = Directory.GetParent(dir)?.FullName;
        }

        return Path.Combine(AppContext.BaseDirectory, "v2_control_key_vectors.json"); // non-existent -> skip
    }
}
