using System.Text.Json;
using Ripcord.Protocol.Halyard.Common.Crypto.V1;
using Xunit;

namespace Ripcord.Protocol.Halyard.Tests;

/// <summary>
/// Byte-exact check of the v2 control-plane key schedule against the console's own HMAC-core outputs
/// (sessions 003/004): <c>sk_p = HMAC-SHA256(Z, 01|p|00|K16|0100)</c>, p=0x09 client→console / 0x08
/// console→client. That is the v1 <see cref="HalyardStreamKeySchedule.DeriveDirection"/> form with K16 in the
/// handshakeKey role — exactly what <see cref="Common.Crypto.V2.HalyardV2SessionCrypto"/> derives in
/// <c>EstablishControl</c>, so proving the schedule here proves the live derivation.
///
/// <para>Fixture <c>docs/protocol/captures/v2_control_key_vectors.json</c> is gitignored (it holds live Z/sk
/// material); generated by <c>v2-validation/extract_v2_key_vectors.py</c>. Skips when absent, so CI (no
/// captures) stays green.</para>
/// </summary>
public class V2ControlKeyScheduleTests
{
    [SkippableFact]
    public void ControlKeySchedule_ReproducesCapturedSkP()
    {
        var fx = LoadOrSkip();
        Assert.NotNull(fx.Control);
        Assert.NotEmpty(fx.Control!);

        foreach (var v in fx.Control!)
        {
            byte[] z = Convert.FromHexString(v.Z);
            byte[] k16 = Convert.FromHexString(v.K16);
            AssertSk(z, k16, 0x09, v.SkClientToConsole);
            AssertSk(z, k16, 0x08, v.SkConsoleToClient);
        }
    }

    private static void AssertSk(byte[] z, byte[] k16, byte purpose, string expectedHex)
    {
        var keys = HalyardStreamKeySchedule.DeriveDirection(z, k16, purpose);
        byte[] sk = [.. keys.AesKey, .. keys.BaseIv]; // sk_p = key(16) || iv-material(16)
        Assert.Equal(expectedHex.ToLowerInvariant(), Convert.ToHexString(sk).ToLowerInvariant());
    }

    private static Fixture LoadOrSkip()
    {
        string path = LocateFixture();
        Skip.IfNot(File.Exists(path),
            $"Captures-folder fixture not present ({path}). Generate it with v2-validation/extract_v2_key_vectors.py.");
        return JsonSerializer.Deserialize<Fixture>(File.ReadAllText(path),
                   new JsonSerializerOptions { PropertyNameCaseInsensitive = true })
               ?? throw new InvalidOperationException("Fixture failed to deserialize.");
    }

    private static string LocateFixture()
    {
        string? env = Environment.GetEnvironmentVariable("RIPCORD_V2_KEY_FIXTURE");
        if (!string.IsNullOrEmpty(env) && File.Exists(env))
            return env;

        string? dir = AppContext.BaseDirectory;
        for (int i = 0; i < 8 && dir is not null; i++)
        {
            string candidate = Path.Combine(dir, "docs", "protocol", "captures", "v2_control_key_vectors.json");
            if (File.Exists(candidate))
                return candidate;
            dir = Directory.GetParent(dir)?.FullName;
        }

        return Path.Combine(AppContext.BaseDirectory, "v2_control_key_vectors.json"); // non-existent -> skip
    }

    private sealed class Fixture
    {
        public List<ControlVector>? Control { get; set; }
    }

    private sealed class ControlVector
    {
        public string Session { get; set; } = "";
        public string Z { get; set; } = "";
        public string K16 { get; set; } = "";
        public string SkClientToConsole { get; set; } = "";
        public string SkConsoleToClient { get; set; } = "";
    }
}
